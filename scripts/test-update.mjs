import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'nikolink-update-test-'));
const target=path.join(temp,'application'),pack=path.join(temp,'update');
fs.mkdirSync(path.join(target,'data'),{recursive:true});fs.mkdirSync(path.join(target,'task-tools'),{recursive:true});fs.mkdirSync(path.join(pack,'payload'),{recursive:true});
fs.copyFileSync(path.join(root,'tools/install-update.ps1'),path.join(pack,'install-update.ps1'));
fs.writeFileSync(path.join(target,'NikoLink.exe'),'old-app');fs.writeFileSync(path.join(target,'data','settings.json'),'private-data');fs.writeFileSync(path.join(target,'task-tools','keep.txt'),'custom-tool');
const content=Buffer.from('new-app'),hash=crypto.createHash('sha256').update(content).digest('hex');
fs.writeFileSync(path.join(pack,'payload','NikoLink.exe'),content);
const manifest={application:'NikoLink',format:1,version:'0.2.0',files:[{path:'NikoLink.exe',sha256:hash}]};
const write=()=>fs.writeFileSync(path.join(pack,'update.json'),JSON.stringify(manifest));write();
const run=()=>spawnSync('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(pack,'install-update.ps1'),'-Target',target],{encoding:'utf8'});
const success=run();assert.equal(success.status,0,success.stderr+success.stdout);
assert.equal(fs.readFileSync(path.join(target,'NikoLink.exe'),'utf8'),'new-app');
assert.equal(fs.readFileSync(path.join(target,'data/settings.json'),'utf8'),'private-data');
assert.equal(fs.readFileSync(path.join(target,'task-tools/keep.txt'),'utf8'),'custom-tool');
const backups=fs.readdirSync(path.join(target,'update-backups'));assert.ok(backups.length);assert.equal(fs.readFileSync(path.join(target,'update-backups',backups[0],'NikoLink.exe'),'utf8'),'old-app');
fs.writeFileSync(path.join(pack,'payload','NikoLink.exe'),'tampered');assert.notEqual(run().status,0);assert.equal(fs.readFileSync(path.join(target,'NikoLink.exe'),'utf8'),'new-app');
manifest.files=[{path:'../data/settings.json',sha256:hash}];write();assert.notEqual(run().status,0);
manifest.files=[{path:'data/settings.json',sha256:hash}];write();assert.notEqual(run().status,0);
console.log('更新器测试通过：替换、备份、数据与用户工具保留、篡改拒绝、越界与数据路径拒绝。');
console.log('测试文件：'+temp);
