import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {runBuiltinTool} from '../opencode-adapter/builtin-tool.mjs';
import {mediaProcess} from '../opencode-adapter/media-process.mjs';
const home=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const input=process.argv[2],output=process.argv[3];
if(!input||!output)throw Error('用法：node scripts/verify-local-media-source.mjs 视频文件 不存在的独立输出目录');
const directory=path.resolve(output);await fs.mkdir(directory,{recursive:false});
const settings=path.join(directory,'test-settings.json');
await fs.writeFile(settings,JSON.stringify({videoSourceSeconds:1800,videoAnalyzeSeconds:1800,videoTranscriptMode:'asr',mediaTimeoutSeconds:1200,videoFrameCount:9,videoFrameStrategy:'uniform'}));
await fs.copyFile(path.resolve(input),path.join(directory,'input.mp4'));
process.env.NIKOLINK_HOME=home;process.env.NIKOLINK_TOOL_SETTINGS=settings;
const started=Date.now();
console.log('Source正式本地视频工具：开始全范围音轨转写与分镜，不调用云端ASR/聊天模型/QQ。');
const video=await runBuiltinTool('video-analysis',{file:'input.mp4'},{workspace:directory});
const transcript=JSON.parse(await fs.readFile(path.join(directory,video.transcriptFile),'utf8'));
assert.equal(transcript.source,'local-asr');assert.ok(transcript.text.length>0);assert.ok(video.image);assert.equal(video.evidence.covered[1],Math.min(video.duration,1800));assert.ok(transcript.segments.at(-1).end>video.duration-30);
console.log('Source正式本地音频工具：独立15秒音频入口验证。');
await mediaProcess(path.join(home,'tools','ffmpeg.exe'),['-nostdin','-v','error','-i',path.join(directory,'input.mp4'),'-t','15','-vn','-ac','1','-ar','16000',path.join(directory,'audio.wav')]);
const audio=await runBuiltinTool('audio-transcribe',{file:'audio.wav'},{workspace:directory});
assert.ok(audio.transcript.length>0);assert.equal(audio.source,'local-asr');assert.equal(audio.image,undefined);
const report={createdAt:new Date().toISOString(),home,duration:video.duration,covered:video.evidence.covered,video:{source:transcript.source,characters:transcript.text.length,segments:transcript.segments.length,speechEnd:transcript.segments.at(-1).end,image:video.image},audio:{source:audio.source,characters:audio.transcript.length,imageAttached:false},elapsedSeconds:(Date.now()-started)/1000,limitations:['未测试QQ收发、工具审批及在线AI最终理解','测试使用独立设置文件，未改用户已保存设置','Python虚拟环境依赖本机基础Python，不能直接声称可移植发行']};
await fs.writeFile(path.join(directory,'verification.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
